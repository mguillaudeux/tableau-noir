export function makeT(lang) {
  const dict = { ...STRINGS.fr, ...(STRINGS[lang] ?? {}) };
  return (key, vars = {}) => String(dict[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}
export const teamName = (name, lang) => (lang === "fr" ? TEAMS_FR[name] ?? name : name);
export const compName = (name, lang) => COMPETITIONS[lang]?.[name] ?? name;
export function stageName(stage, lang) {
  if (stage.startsWith("Group ") && stage !== "Group Stage") return lang === "fr" ? `Groupe ${stage.slice(6)}` : stage;
  return STAGES[lang]?.[stage] ?? stage;
}
